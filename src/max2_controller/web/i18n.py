def i18n_json() -> str:
    """JSON słowników — bezpieczny do wklejenia w <script>."""
    payload = {"langs": LANGS, "strings": STRINGS}
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")


I18N_BOOT_JS = r"""
const LC_LANG_KEY = 'lc_lang';
const LC_I18N = __I18N_JSON__;
const I18N = LC_I18N.strings || {};
const LC_LANGS = {};
(LC_I18N.langs || []).forEach(function (pair) { LC_LANGS[pair[0]] = pair[1]; });

function detectLang(){
  try {
    const saved = localStorage.getItem(LC_LANG_KEY);
    if (saved && I18N[saved]) return saved;
  } catch (e) {}
  const nav = String((navigator.languages && navigator.languages[0]) || navigator.language || 'pl').toLowerCase();
  const short = nav.slice(0, 2);
  if (I18N[short]) return short;
  return 'pl';
}

let LANG = 'pl';

function t(key, vars){
  const pack = I18N[LANG] || I18N.pl || {};
  let s = pack[key];
  if (s == null) s = (I18N.en || {})[key];
  if (s == null) s = (I18N.pl || {})[key];
  if (s == null) s = key;
  if (vars){
    Object.keys(vars).forEach(function (k) {
      s = String(s).split('{' + k + '}').join(String(vars[k]));
    });
  }
  return s;
}

function applyI18n(){
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  const title = document.querySelector('title[data-i18n]');
  if (title) document.title = t(title.getAttribute('data-i18n'));
  document.querySelectorAll('[data-lang-select]').forEach(function (sel) {
    sel.value = LANG;
  });
  try { document.dispatchEvent(new CustomEvent('lc-lang', { detail: LANG })); } catch (e) {}
}

function setLang(lang){
  if (!I18N[lang]) lang = 'pl';
  LANG = lang;
  try { localStorage.setItem(LC_LANG_KEY, lang); } catch (e) {}
  applyI18n();
}

function fillLangSelect(sel){
  if (!sel) return;
  const cur = sel.value;
  sel.innerHTML = Object.keys(LC_LANGS).map(function (k) {
    return '<option value="' + k + '">' + LC_LANGS[k] + '</option>';
  }).join('');
  sel.value = cur || LANG;
  sel.onchange = function () { setLang(sel.value); };
}

function initI18n(){
  LANG = detectLang();
  document.querySelectorAll('[data-lang-select]').forEach(fillLangSelect);
  applyI18n();
}
"""


def i18n_boot_script() -> str:
    return "<script>" + I18N_BOOT_JS.replace("__I18N_JSON__", i18n_json()) + "</script>"


